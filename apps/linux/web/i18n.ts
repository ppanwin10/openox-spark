export const locale = /^zh\b/i.test(navigator.language) ? "zh-Hans" : "en";
const strings = locale === "zh-Hans" ? zh : en;
export type StringKey = keyof Strings;
export function t(key: StringKey, values: Record<string, string | number> = {}) {
  return strings[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}
