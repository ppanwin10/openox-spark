let hostPatterns: [RegExp, string][] | undefined;
const escapeRegExp = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

function hostLine(line: string) {
  const exact = hostZh[line];
  if (exact !== undefined) return exact;
  hostPatterns ??= Object.entries(hostZh).filter(([key]) => key.includes("{0}"))
    .map(([key, value]) => [new RegExp(`^${key.split(/\{\d\}/).map(escapeRegExp).join("(.+?)")}$`), value]);
  for (const [pattern, value] of hostPatterns) {
    const match = pattern.exec(line);
    if (match) return value.replace(/\{(\d)\}/g, (_, index: string) => match[Number(index) + 1] ?? "");
  }
  return line;
}

export function hostText(text: string): string;
export function hostText(text: string | undefined): string | undefined;
export function hostText(text: string | undefined) {
  return text && locale === "zh-Hans" ? text.split("\n").map(hostLine).join("\n") : text;
}
